PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS Propietarios (
 Id INTEGER PRIMARY KEY AUTOINCREMENT, Nombre TEXT NOT NULL, DPI TEXT UNIQUE,
 Telefono TEXT NOT NULL, Correo TEXT
);
CREATE TABLE IF NOT EXISTS Mascotas (
 Id INTEGER PRIMARY KEY AUTOINCREMENT, Nombre TEXT NOT NULL, Especie TEXT NOT NULL,
 Raza TEXT, Sexo TEXT, FechaNacimiento TEXT, Peso REAL CHECK(Peso IS NULL OR Peso > 0),
 PropietarioId INTEGER NOT NULL, Observaciones TEXT,
 FOREIGN KEY(PropietarioId) REFERENCES Propietarios(Id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS Veterinarios (
 Id INTEGER PRIMARY KEY AUTOINCREMENT, Nombre TEXT NOT NULL, Colegiado TEXT UNIQUE,
 Telefono TEXT, Correo TEXT, Especialidad TEXT
);
CREATE TABLE IF NOT EXISTS Citas (
 Id INTEGER PRIMARY KEY AUTOINCREMENT, MascotaId INTEGER NOT NULL, VeterinarioId INTEGER NOT NULL,
 FechaHora TEXT NOT NULL, Motivo TEXT NOT NULL, Estado TEXT NOT NULL DEFAULT 'Programada'
 CHECK(Estado IN ('Programada','Atendida','Cancelada')),
 FOREIGN KEY(MascotaId) REFERENCES Mascotas(Id) ON DELETE RESTRICT,
 FOREIGN KEY(VeterinarioId) REFERENCES Veterinarios(Id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS ConsultasClinicas (
 Id INTEGER PRIMARY KEY AUTOINCREMENT, CitaId INTEGER, MascotaId INTEGER NOT NULL,
 Fecha TEXT NOT NULL, Sintomas TEXT NOT NULL, Diagnostico TEXT NOT NULL,
 Tratamiento TEXT, Medicamentos TEXT, ProximaVisita TEXT,
 FOREIGN KEY(CitaId) REFERENCES Citas(Id) ON DELETE SET NULL,
 FOREIGN KEY(MascotaId) REFERENCES Mascotas(Id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS IX_Mascotas_Propietario ON Mascotas(PropietarioId);
CREATE INDEX IF NOT EXISTS IX_Citas_Fecha ON Citas(FechaHora);
CREATE INDEX IF NOT EXISTS IX_Consultas_Mascota ON ConsultasClinicas(MascotaId, Fecha);
